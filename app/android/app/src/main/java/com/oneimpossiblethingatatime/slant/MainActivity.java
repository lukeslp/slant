package com.oneimpossiblethingatatime.slant;

import android.content.ClipData;
import android.content.Intent;
import android.content.res.Configuration;
import android.net.Uri;
import android.os.Build;
import android.os.Bundle;
import android.util.Base64;
import android.util.Log;
import android.view.View;
import android.view.ViewGroup;
import android.view.Window;
import android.view.WindowInsets;
import android.view.WindowInsetsController;
import android.view.WindowManager;
import android.webkit.JavascriptInterface;
import android.webkit.WebView;
import android.widget.FrameLayout;

import androidx.activity.OnBackPressedCallback;
import androidx.core.content.FileProvider;

import com.getcapacitor.BridgeActivity;
import com.getcapacitor.WebViewListener;

import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;

/**
 * Slant's Android shell. The game itself is the sealed payload in assets/public
 * (app/www, generated by scripts/export-www.py); this class only frames it:
 * full screen, clear of camera cutouts, with system Back closing the game's
 * sheets before it leaves the app, and the Download button's picture handed
 * to the share sheet (app/native/native.js sends it here).
 */
@SuppressWarnings("deprecation")
public class MainActivity extends BridgeActivity {
    private GameViewport gameViewport;
    private int lastDensityDpi;

    // Closes the topmost open <dialog> (Settings, How to play) and says
    // whether there was one. close() fires the dialog's own
    // close event, so the game restores focus as it does for its X button.
    private static final String CLOSE_TOP_SHEET_JS =
        "(function(){var d=document.querySelectorAll('dialog[open]');" +
        "if(!d.length)return false;d[d.length-1].close();return true;})()";

    // Reports the page color to the shell now and whenever the theme changes,
    // so the strip left beside a camera cutout matches the board's background.
    private static final String WATCH_BACKDROP_JS =
        "(function(){if(window.__slantBackdrop||!window.SlantShell)return;window.__slantBackdrop=1;" +
        "var send=function(){try{SlantShell.setBackdrop(getComputedStyle(document.body).backgroundColor);}catch(e){}};" +
        "new MutationObserver(function(){requestAnimationFrame(send);})" +
        ".observe(document.documentElement,{attributes:true,attributeFilter:['data-theme','style','class']});" +
        "try{matchMedia('(prefers-color-scheme: dark)').addEventListener('change',function(){requestAnimationFrame(send);});}catch(e){}" +
        "send();})()";

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        bridgeBuilder.addWebViewListener(new WebViewListener() {
            @Override
            public void onPageLoaded(WebView webView) {
                if (isOwnPage(webView.getUrl())) webView.evaluateJavascript(WATCH_BACKDROP_JS, null);
            }
        });
        super.onCreate(savedInstanceState);
        lastDensityDpi = getResources().getConfiguration().densityDpi;
        if (getBridge() != null) {
            WebView webView = getBridge().getWebView();
            webView.addJavascriptInterface(new Backdrop(), "SlantShell");
            // The game draws its own clear area around the board; no overscroll glow.
            webView.setOverScrollMode(View.OVER_SCROLL_NEVER);
            ViewGroup content = findViewById(android.R.id.content);
            View bridgeRoot = content.getChildAt(0);
            content.removeView(bridgeRoot);
            gameViewport = new GameViewport(this);
            gameViewport.addView(bridgeRoot, new FrameLayout.LayoutParams(
                ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.MATCH_PARENT));
            content.addView(gameViewport, new FrameLayout.LayoutParams(
                ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.MATCH_PARENT));
        }
        keepScreenImmersive();
        getOnBackPressedDispatcher().addCallback(this, new OnBackPressedCallback(true) {
            @Override
            public void handleOnBackPressed() {
                handleBack(this);
            }
        });
    }

    /** System Back closes an open sheet; with none open it leaves the app. */
    private void handleBack(OnBackPressedCallback callback) {
        WebView webView = getBridge() != null ? getBridge().getWebView() : null;
        if (webView == null || !isOwnPage(webView.getUrl())) {
            leaveApp(callback);
            return;
        }
        webView.evaluateJavascript(CLOSE_TOP_SHEET_JS, result -> {
            if (!"true".equals(result) && !isFinishing() && !isDestroyed()) leaveApp(callback);
        });
    }

    private void leaveApp(OnBackPressedCallback callback) {
        callback.setEnabled(false);
        getOnBackPressedDispatcher().onBackPressed();
        callback.setEnabled(true);
    }

    /** The bundled game page, never a foreign URL. */
    private static boolean isOwnPage(String url) {
        if (url == null) return false;
        Uri uri = Uri.parse(url);
        return "https".equals(uri.getScheme()) && "localhost".equals(uri.getHost())
            && uri.getUserInfo() == null && (uri.getPort() == -1 || uri.getPort() == 443);
    }

    private final class Backdrop {
        @JavascriptInterface
        public void setBackdrop(String css) {
            Integer color = BackdropColor.parse(css);
            if (color == null) return;
            runOnUiThread(() -> {
                if (gameViewport != null) gameViewport.setBackgroundColor(color);
                // The band beside a camera cutout can sit outside the content view, where
                // the window background (the system theme's page color) shows. Without this
                // a player who picks Dark on a light-themed phone gets a white band on top.
                getWindow().getDecorView().setBackgroundColor(color);
            });
        }

        /** A puzzle picture from the Download button, as base64 PNG. Opens the share sheet. */
        @JavascriptInterface
        public void savePicture(String name, String base64) {
            String file = SharedPictures.safeName(name);
            byte[] png;
            try {
                png = Base64.decode(base64, Base64.DEFAULT);
            } catch (IllegalArgumentException e) {
                return;
            }
            if (!SharedPictures.isPng(png)) return;
            runOnUiThread(() -> sharePicture(file, png));
        }
    }

    private void sharePicture(String name, byte[] png) {
        if (isFinishing() || isDestroyed()) return;
        try {
            File dir = new File(getCacheDir(), "shared");
            if (!dir.isDirectory() && !dir.mkdirs()) return;
            // Keep recent pictures: an app the player shared to (a mail draft, say)
            // may read its file later. Older ones go.
            long cutoff = System.currentTimeMillis() - 60 * 60 * 1000L;
            File[] old = dir.listFiles();
            if (old != null) for (File f : old) if (f.lastModified() < cutoff) f.delete();
            File out = new File(dir, name);
            try (FileOutputStream stream = new FileOutputStream(out)) {
                stream.write(png);
            }
            Uri uri = FileProvider.getUriForFile(this, getPackageName() + ".pictures", out);
            Intent send = new Intent(Intent.ACTION_SEND)
                .setType("image/png")
                .putExtra(Intent.EXTRA_STREAM, uri)
                .addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION);
            send.setClipData(ClipData.newRawUri(name, uri));
            startActivity(Intent.createChooser(send, null));
        } catch (IOException | RuntimeException e) {
            Log.w("Slant", "Could not share the picture", e);
        }
    }

    @Override
    public void onResume() {
        super.onResume();
        keepScreenImmersive();
    }

    @Override
    public void onWindowFocusChanged(boolean hasFocus) {
        super.onWindowFocusChanged(hasFocus);
        if (hasFocus) keepScreenImmersive();
    }

    @Override
    public void onConfigurationChanged(Configuration newConfig) {
        int oldDensity = lastDensityDpi;
        lastDensityDpi = newConfig.densityDpi;
        super.onConfigurationChanged(newConfig);
        keepScreenImmersive();
        // A display-size change while the game is open leaves the page laid out
        // for the old density (seen on the emulator: the board slid off center).
        // The game saves every move, so a reload only redraws it.
        if (oldDensity != 0 && oldDensity != newConfig.densityDpi && getBridge() != null) {
            getBridge().getWebView().reload();
        }
    }

    private void keepScreenImmersive() {
        Window activityWindow = getWindow();
        // Keep the WebView in the real app window so fold and compatibility-frame
        // resizes produce an actual viewport resize instead of drawing off-window.
        activityWindow.clearFlags(WindowManager.LayoutParams.FLAG_LAYOUT_NO_LIMITS);
        activityWindow.getDecorView().setSystemUiVisibility(
            View.SYSTEM_UI_FLAG_FULLSCREEN |
            View.SYSTEM_UI_FLAG_HIDE_NAVIGATION |
            View.SYSTEM_UI_FLAG_IMMERSIVE_STICKY |
            View.SYSTEM_UI_FLAG_LAYOUT_FULLSCREEN |
            View.SYSTEM_UI_FLAG_LAYOUT_HIDE_NAVIGATION |
            View.SYSTEM_UI_FLAG_LAYOUT_STABLE
        );
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
            activityWindow.setDecorFitsSystemWindows(false);
            WindowInsetsController controller = activityWindow.getInsetsController();
            if (controller != null) {
                controller.setSystemBarsBehavior(WindowInsetsController.BEHAVIOR_SHOW_TRANSIENT_BARS_BY_SWIPE);
                controller.hide(WindowInsets.Type.systemBars());
            }
        }
        if (gameViewport != null) gameViewport.requestApplyInsets();
    }
}
